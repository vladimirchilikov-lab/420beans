module.exports = async (req, res) => {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  try {
    if (!process.env.GROQ_API_KEY) {
      throw new Error('Missing GROQ_API_KEY environment variable');
    }

    const { messages, lang } = req.body || {};

    if (!Array.isArray(messages) || messages.length === 0) {
      return res.status(400).json({ error: 'Missing messages' });
    }

    const cleanMessages = messages
      .filter(
        (m) =>
          m &&
          (m.role === 'user' || m.role === 'assistant') &&
          typeof m.content === 'string'
      )
      .slice(-MAX_TURNS)
      .map((m) => ({
        role: m.role,
        content: m.content.slice(0, MAX_MSG_LEN),
      }));

    if (
      !cleanMessages.length ||
      cleanMessages[cleanMessages.length - 1].role !== 'user'
    ) {
      return res.status(400).json({
        error: 'Last message must be from the user',
      });
    }

    let products = [];

    if (
      process.env.SUPABASE_URL &&
      process.env.SUPABASE_SERVICE_KEY
    ) {
      const supabase = createClient(
        process.env.SUPABASE_URL,
        process.env.SUPABASE_SERVICE_KEY
      );

      const { data, error } = await supabase
        .from('products')
        .select('name, description, price, category')
        .order('created_at', { ascending: true });

      if (error) {
        console.error('Supabase product query error:', error.message);
      } else {
        products = data || [];
      }
    }

    const catalogBlock = buildCatalogBlock(products);
    const systemPrompt = buildSystemPrompt(
      catalogBlock,
      lang === 'en' ? 'en' : 'bg'
    );

    const response = await fetch(
      'https://api.groq.com/openai/v1/chat/completions',
      {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${process.env.GROQ_API_KEY}`,
        },
        body: JSON.stringify({
          model: GROQ_MODEL,
          max_tokens: MAX_TOKENS,
          temperature: 0.5,
          messages: [
            {
              role: 'system',
              content: systemPrompt,
            },
            ...cleanMessages,
          ],
        }),
      }
    );

    if (!response.ok) {
      const errText = await response.text();

      console.error(
        'Groq API error:',
        response.status,
        errText
      );

      throw new Error(`AI service error ${response.status}`);
    }

    const data = await response.json();
    const reply =
      data.choices?.[0]?.message?.content?.trim() || '';

    return res.status(200).json({
      reply: reply || 'Извинявай, не успях да формулирам отговор. Опитай отново.',
    });
  } catch (err) {
    console.error('Chat error:', err);

    return res.status(500).json({
      error: 'Failed to get a response',
      detail: 'В момента чатът не е достъпен. Опитай отново след малко.',
    });
  }
};
